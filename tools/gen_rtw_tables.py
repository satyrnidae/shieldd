"""One-off: convert rtw88 rtw8821a_table.c MAC/AGC/BB/RF arrays into rtlusb/src/tables.rs."""
import re, sys
src = open(sys.argv[1], encoding='utf-8').read()
out = ["// Generated by tools/gen_rtw_tables.py from rtw88 rtw8821a_table.c. Don't edit.",
       "// rtw88 is GPL-2.0 OR BSD-3-Clause, Copyright(c) 2024 Realtek Corporation.", ""]
for name, rust in [("rtw8821a_mac", "MAC"), ("rtw8821a_agc", "AGC"), ("rtw8821a_bb", "BB"), ("rtw8821a_rf_a", "RF_A")]:
    m = re.search(r"static const u32 %s\[\] = \{(.*?)\};" % name, src, re.S)
    nums = re.findall(r"0[xX][0-9A-Fa-f]+|\b\d+\b", re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S))
    assert len(nums) % 2 == 0, name
    # Every entry is a token between commas, so the counts must agree
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    assert len(nums) == len([t for t in body.split(",") if t.strip()]), name
    out.append(f"pub static {rust}: &[(u32, u32)] = &[")
    for i in range(0, len(nums), 2):
        out.append(f"    ({int(nums[i], 0):#010x}, {int(nums[i + 1], 0):#010x}),")
    out.append("];\n")
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write("\n".join(out))
